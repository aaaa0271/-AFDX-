"""Generate the configurable security adapter, including RX timestamp metadata.

Eight-port demos own real startup/application logic and are maintained separately.
"""
from pathlib import Path
import re,hashlib
R=Path(__file__).resolve().parents[1]
source=R/'reference_core/rtl/AFDX_competition_top.v'
if not source.is_file():source=R/'rtl/AFDX_competition_top.v'
s=source.read_text(encoding='utf-8')
a=s.index('module AFDX_competition_top');b=s.index(');\nfunction',a)
header=s[a:b].replace('module AFDX_competition_top','module AFDX_security_plugin_top',1)
# These are private outer-queue connections, not external configuration pins.
header=header.replace(',RX_TIMESTAMP_DELAYS=0','')
header=header.replace(',\n input wire [63:0] data_a_rx_delay,data_b_rx_delay','')
header=header.replace(')(\n',', parameter integer SECURITY_BOOT_MODE=2\n)(\n',1)
param_part=header[:header.index(')(\n')]
param_text=re.sub(r'//[^\n]*','',param_part)
param_text=param_text[param_text.index('#(')+2:].rstrip()[:-1]
segments=[];depth=0;start=0
for index,char in enumerate(param_text):
 if char in '([{':depth+=1
 elif char in ')]}':depth-=1
 elif char==',' and depth==0:segments.append(param_text[start:index]);start=index+1
segments.append(param_text[start:])
params=[re.findall(r'\b[A-Za-z_]\w*\b',part.split('=',1)[0])[-1] for part in segments]
assert len(params)==23 and len(params)==len(set(params)) and 'SUBVL_MAX_MESSAGE' in params and 'SNMP_USER_NAME' in params
port_part=header[header.index(')(\n')+3:]
clean=re.sub(r'//[^\n]*','',port_part);clean=re.sub(r'\[[^\]]+\]','',clean)
names=[n for n in re.findall(r'\b[A-Za-z_]\w*\b',clean) if n not in ('input','output','wire')]
assert len(names)==len(set(names)) and all(n in names for n in ('data_a_rxd','data_b_rxd','service_cfg_we'))
extra=''',
 input wire sec_cfg_write,sec_cfg_read,input wire [15:0] sec_cfg_address,input wire [31:0] sec_cfg_wdata,
 output wire sec_cfg_ready,sec_cfg_error,sec_cfg_pending,sec_cfg_commit_pulse,output wire [31:0] sec_cfg_rdata,
 output wire [1:0] sec_mode,output wire [31:0] sec_epoch,
 output wire sec_event_valid,input wire sec_event_ready,output wire [159:0] sec_event_record,
 output wire sec_alarm,output wire [3:0] sec_time_flags,
 output wire [31:0] sec_time_alarms,sec_would_allow,sec_would_block,sec_queue_overflows,sec_event_overflows,sec_ab_conflicts,sec_hash_failures
);
'''
# The original default helper is needed for exactly the same parameter defaults.
f=s[s.index('function [SERVICE_DOMAINS*32-1:0] default_service_ips;'):s.index('endfunction')+len('endfunction')]
out='`timescale 1ns/1ps\n// Generated by scripts/generate_wrapper.py; preserves outer RX timestamps.\n'+header.rstrip()+extra+f+'\n'
out+='''wire [7:0] guarded_a,guarded_b;wire guarded_av,guarded_bv,guarded_ae,guarded_be;
wire [63:0] guarded_a_delay,guarded_b_delay;
reg [SERVICE_DOMAIN_WIDTH-1:0] prior_domain;
always @(posedge clk)begin if(rst)prior_domain<=service_app_domain;else prior_domain<=service_app_domain;end
wire time_reanchor=prior_domain!==service_app_domain;
'''
out+='AFDX_competition_top #(\n'+',\n'.join(' .'+p+'('+p+')' for p in params if p!='SECURITY_BOOT_MODE')+',.RX_TIMESTAMP_DELAYS(1)\n) core(\n .data_a_rx_delay(guarded_a_delay),.data_b_rx_delay(guarded_b_delay),\n'
route={'data_a_rxd':'guarded_a','data_b_rxd':'guarded_b','data_a_rx_dv':'guarded_av','data_b_rx_dv':'guarded_bv','data_a_rx_er':'guarded_ae','data_b_rx_er':'guarded_be'}
out+=',\n'.join(' .'+n+'('+route.get(n,n)+')' for n in names)+'\n);\n'
out+='''afdx_security_plugin #(.BOOT_MODE(SECURITY_BOOT_MODE),.CLK_HZ(CLK_HZ)) security(
 .clk(clk),.rst(rst),.a_rx(data_a_rxd),.b_rx(data_b_rxd),.a_rx_valid(data_a_rx_dv),.b_rx_valid(data_b_rx_dv),.a_rx_error(data_a_rx_er),.b_rx_error(data_b_rx_er),
 .a_tx(data_a_txd),.b_tx(data_b_txd),.a_tx_valid(data_a_tx_en),.b_tx_valid(data_b_tx_en),.a_tx_error(data_a_tx_er),.b_tx_error(data_b_tx_er),
 .core_a_rx(guarded_a),.core_b_rx(guarded_b),.core_a_valid(guarded_av),.core_b_valid(guarded_bv),.core_a_error(guarded_ae),.core_b_error(guarded_be),.core_a_rx_delay(guarded_a_delay),.core_b_rx_delay(guarded_b_delay),
 .core_safe(!loading&&!management_busy&&!data_a_tx_en&&!data_b_tx_en),.target_id(hardware_id),.rtc_locked(rtc_locked),.utc_ntp(utc_ntp),.monotonic_ticks(monotonic_ticks),.time_reanchor(time_reanchor),
 .cfg_write(sec_cfg_write),.cfg_read(sec_cfg_read),.cfg_address(sec_cfg_address),.cfg_wdata(sec_cfg_wdata),.cfg_ready(sec_cfg_ready),.cfg_error(sec_cfg_error),.cfg_pending(sec_cfg_pending),.cfg_commit_pulse(sec_cfg_commit_pulse),.cfg_rdata(sec_cfg_rdata),
 .mode(sec_mode),.epoch(sec_epoch),.event_valid(sec_event_valid),.event_ready(sec_event_ready),.event_record(sec_event_record),.alarm(sec_alarm),.time_flags(sec_time_flags),.time_alarms(sec_time_alarms),
 .would_allow(sec_would_allow),.would_block(sec_would_block),.queue_overflows(sec_queue_overflows),.event_overflows(sec_event_overflows),.ab_conflicts(sec_ab_conflicts),.hash_failures(sec_hash_failures),.idle());
endmodule
'''
Path(R/'rtl/AFDX_security_plugin_top.v').write_text(out)
print('WRAPPER_GENERATED baseline ports',len(names),'parameters',len(params))
