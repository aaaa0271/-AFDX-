#!/usr/bin/env python3
"""Deterministic post-training quantization. Uses training inputs, never test labels."""
import hashlib
import json
import sys
from pathlib import Path
import numpy as np

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))
from afdx_ai_hw.fixed import load_arrays, round_away, integer_tcn, sha, write_json


def hex_file(path, data, bits):
    a = np.asarray(data).reshape(-1)
    Path(path).write_text(''.join(f'{int(v) & ((1 << bits) - 1):0{bits // 4}x}\n' for v in a))


def export(root=ROOT, weight_bits=16):
    root = Path(root)
    p = load_arrays(root / 'source_model/models/temporal.npz')
    keys = ('K1', 'b1', 'K2', 'b2', 'W', 'b')
    sys.path.insert(0, str(root / 'source_model'))
    from afdx_ext.nn import tcn
    data = load_arrays(root / 'source_model/data/train.npz')
    z = (np.log1p(data['X']) - p['mean']) / p['scale']
    float_out, (_, h1, _, h2, _) = tcn(p, z, cache=True)
    # Fixed binary point per layer; calibration headroom determined only on training inputs.
    def activation_q(a):
        maximum = max(1., float(np.max(np.abs(a))))
        return min(12, max(4, int(np.floor(np.log2(32767 / (maximum * 2))))))
    qs = [activation_q(z), activation_q(h1), activation_q(h2), activation_q(float_out)]
    limit = (1 << (weight_bits - 1)) - 1
    wqs = [np.floor(np.log2(limit / np.max(np.abs(p[k]), axis=tuple(range(p[k].ndim - 1))))).astype(int)
           for k in ('K1', 'K2', 'W')]
    shifts = [qs[i] + wqs[i] - qs[i + 1] for i in range(3)]
    if any(np.any((s < 0) | (s > 31)) for s in shifts):
        raise ValueError('quantization requires unsupported shift')
    q = {}
    for i, (wk, bk) in enumerate((('K1', 'b1'), ('K2', 'b2'), ('W', 'b'))):
        q[wk] = round_away(p[wk].astype(np.float64) * (1 << wqs[i])).astype(np.int16 if weight_bits == 16 else np.int8)
        bias = round_away(p[bk].astype(np.float64) * (1 << (qs[i] + wqs[i])))
        if np.any(np.abs(bias) >= (1 << 31)):
            raise ValueError('bias overflow')
        q[bk] = bias.astype(np.int32)
    th = p['thresholds'].astype(np.float64)
    q['thresholds_q'] = np.ceil(np.log(th / (1 - th)) * (1 << qs[3])).astype(np.int16)
    for k in ('mean', 'scale', 'reg_mean', 'reg_scale', 'radius'):
        q[k] = p[k]
    fingerprint = hashlib.sha256()
    fingerprint.update(bytes.fromhex(sha(root / 'source_model/models/temporal.npz')))
    wqs = [a.tolist() for a in wqs]
    shifts = [a.tolist() for a in shifts]
    fingerprint.update(json.dumps(dict(qs=qs, wqs=wqs, shifts=shifts), sort_keys=True).encode())
    for k in sorted(q):
        fingerprint.update(k.encode() + q[k].tobytes())
    tag = fingerprint.hexdigest()[:8]
    cfg = dict(schema=1, name=f'afdx_tcn_int{weight_bits}_r1', model_tag=tag,
               source_model_sha256=sha(root / 'source_model/models/temporal.npz'),
               q_input=qs[0], q_h1=qs[1], q_h2=qs[2], q_output=qs[3],
               weight_fraction_bits=wqs, shifts=shifts, accumulator_bits=48,
               activation_bits=16, weight_bits=weight_bits, bias_bits=32,
               rounding='nearest, ties away from zero', zero_padding='causal, left',
               dilation=[1, 2], activation='relu', pooling='mean over 8, rounded once',
               threshold_comparison='integer_logit >= ceil(logit(float_threshold)*2**q_output)',
               calibration='train inputs only; thresholds inherited from source validation',
               retrained_for_hardware=False, training_domain='synthetic abstract packet-service traces',
               parameters=1961, weight_payload_bytes=1920 * weight_bits // 8, bias_payload_bytes=164,
               macs_per_job=13344, compute_cycles=14035,
               artifacts={})
    np.savez_compressed(root / 'models/quantized.npz', **q)
    weights = np.concatenate([q['K1'].transpose(2, 0, 1).reshape(-1),
                              q['K2'].transpose(2, 0, 1).reshape(-1), q['W'].T.reshape(-1)])
    biases = np.concatenate([q['b1'], q['b2'], q['b']])
    hex_file(root / 'rtl/weights.mem', weights, weight_bits)
    hex_file(root / 'rtl/biases.mem', biases, 32)
    hex_file(root / 'rtl/thresholds.mem', q['thresholds_q'], 16)
    hex_file(root / 'rtl/shifts.mem', np.concatenate(shifts), 8)
    header = '// Generated by scripts/export_model.py; fixed ROM model.\n'
    header += f"localparam [31:0] MODEL_TAG = 32'h{tag};\n"
    header += f'localparam integer WEIGHT_BITS = {weight_bits};\n'
    header += f'localparam integer Q_OUTPUT = {qs[3]};\n'
    (root / 'rtl/ai_model_params.vh').write_text(header)
    for f in ('models/quantized.npz', 'rtl/weights.mem', 'rtl/biases.mem',
              'rtl/thresholds.mem', 'rtl/shifts.mem', 'rtl/ai_model_params.vh'):
        cfg['artifacts'][f] = sha(root / f)
    write_json(root / 'models/model.json', cfg)
    # Verify theoretical accumulator bounds for every neuron, including arbitrary int16 inputs.
    bounds = {}
    for i, (wk, bk) in enumerate((('K1', 'b1'), ('K2', 'b2'), ('W', 'b'))):
        w = q[wk].astype(np.int64)
        fan_axes = (0, 1) if w.ndim == 3 else (0,)
        upper = np.sum(np.abs(w), axis=fan_axes) * 32768 + np.abs(q[bk].astype(np.int64))
        if np.any(upper >= (1 << 47)):
            raise ValueError('48-bit accumulator bound exceeded')
        bounds[wk] = dict(maximum_absolute_accumulator=int(upper.max()),
                          minimum_signed_bits=int(int(upper.max()).bit_length() + 1))
    write_json(root / 'reports/arithmetic_bounds.json', dict(
        accumulator_bits=48, product_bits=16 + weight_bits, layers=bounds,
        arbitrary_int16_inputs_supported_numerically=True,
        arbitrary_inputs_valid_for_diagnosis=False,
        pooling_maximum_sum=8 * 32767, parameter_payload_bytes=len(weights) * weight_bits // 8 + len(biases) * 4,
        formula_compute_cycles=128 * (1 + 54 + 1) + 128 * (1 + 48 + 1) + 16 * (1 + 8 + 1) + 9 * (1 + 32 + 1) + 1))
    return cfg


if __name__ == '__main__':
    import argparse
    parser = argparse.ArgumentParser()
    parser.add_argument('--weight-bits', type=int, choices=(8, 16), default=16)
    args = parser.parse_args()
    print(json.dumps(export(weight_bits=args.weight_bits), indent=2))
